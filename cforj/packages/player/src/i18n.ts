export type PlayerT = (key: string) => string

export const PlayerLocaleContext = createContext<PlayerLocale>('en')

export function usePlayerT(): PlayerT {
  const locale = useContext(PlayerLocaleContext)
  return (key: string) => translations[locale]?.[key] ?? translations.en[key] ?? key
}
