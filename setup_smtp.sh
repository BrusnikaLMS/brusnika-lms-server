#!/bin/bash

# ============================================================
# SETUP_SMTP.SH — Подключение собственного почтового сервера (SMTP)
# SETUP_SMTP.SH — Connect a custom SMTP mail server
# ============================================================
#   Запрашивает параметры SMTP и генерирует lms/local/include/smtp.local.php —
#   файл, который читает бэкенд ЛМС (Uni\LocalConfig, служба "smtp") для
#   отправки писем (уведомления, сброс пароля, приглашения).
#   Можно запускать как во время первоначальной настройки, так и в любой
#   момент позже — чтобы сменить почтовый сервер, просто запустите скрипт
#   заново и перезапустите контейнер php.
#
#   Prompts for SMTP parameters and generates lms/local/include/smtp.local.php —
#   the file the LMS backend (Uni\LocalConfig, "smtp" service) reads to send
#   mail (notifications, password reset, invitations).
#   Can be run during initial setup or at any later point — to switch the
#   mail server, just re-run this script and restart the php container.
# ============================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
info()    { echo -e "${BLUE}ℹ️  $1${NC}"; }
success() { echo -e "${GREEN}✅ $1${NC}"; }
warning() { echo -e "${YELLOW}⚠️  $1${NC}"; }
error()   { echo -e "${RED}❌ $1${NC}"; }

echo ""
echo "=============================================="
echo "   📧 Brusnika LMS — настройка SMTP"
echo "   📧 Brusnika LMS — SMTP setup"
echo "=============================================="
echo ""
info "Поддерживается любой почтовый сервер: с авторизацией и без, TLS/SSL/без шифрования, любой порт."
info "Any mail server is supported: with or without auth, TLS/SSL/no encryption, any port."
echo ""

# ============================================================
# 1. ПАРАМЕТРЫ SMTP / SMTP PARAMETERS
# ============================================================
read -p "SMTP-сервер (например: smtp.yandex.ru) / SMTP host (e.g. smtp.yandex.ru): " SMTP_HOST
[ -z "$SMTP_HOST" ] && { error "SMTP-сервер обязателен / SMTP host is required"; exit 1; }

read -p "SMTP-порт / SMTP port [587]: " SMTP_PORT
SMTP_PORT=${SMTP_PORT:-587}

echo ""
echo "Шифрование / Encryption:"
echo "  1) tls  — STARTTLS (по умолчанию / default, порт обычно 587)"
echo "  2) ssl  — implicit SSL (порт обычно 465)"
echo "  3) none — без шифрования, только для сервера внутри закрытого периметра / unencrypted, internal perimeter only"
read -p "Выбор (1/2/3) / Choice (1/2/3) [1]: " SECURE_CHOICE
SECURE_CHOICE=${SECURE_CHOICE:-1}
case "$SECURE_CHOICE" in
  2) SMTP_SECURE="ssl" ;;
  3) SMTP_SECURE="none" ;;
  *) SMTP_SECURE="tls" ;;
esac

if [ "$SMTP_SECURE" = "none" ]; then
  warning "Без шифрования пароль SMTP уходит в открытом виде — используйте только для релея внутри изолированной сети."
  warning "Unencrypted: the SMTP password travels in plaintext — only use this for a relay inside an isolated network."
  read -p "Продолжить? / Continue? (y/N): " CONFIRM_NONE
  if [[ ! "$CONFIRM_NONE" =~ ^[Yy]$ ]]; then
    error "Отменено / Cancelled"
    exit 1
  fi
fi

echo ""
read -p "Требуется авторизация на SMTP-сервере? / Does the SMTP server require authentication? (Y/n): " USE_AUTH
USE_AUTH=${USE_AUTH:-Y}

SMTP_FROM_EMAIL=""
SMTP_PASSWORD=""

if [[ "$USE_AUTH" =~ ^[Yy]$ ]]; then
  SMTP_AUTH="1"
  read -p "Email отправителя (он же логин) / Sender email (used as login): " SMTP_FROM_EMAIL
  [ -z "$SMTP_FROM_EMAIL" ] && { error "Email отправителя обязателен при включённой авторизации / Sender email is required when auth is enabled"; exit 1; }
  read -s -p "Пароль SMTP / SMTP password: " SMTP_PASSWORD
  echo ""
  [ -z "$SMTP_PASSWORD" ] && { error "Пароль обязателен при включённой авторизации / Password is required when auth is enabled"; exit 1; }
else
  SMTP_AUTH="0"
  read -p "Email отправителя (поле \"От кого\" в письмах) / Sender email (used as the \"From\" address): " SMTP_FROM_EMAIL
  [ -z "$SMTP_FROM_EMAIL" ] && { error "Email отправителя обязателен / Sender email is required"; exit 1; }
fi

# ============================================================
# 2. ГЕНЕРАЦИЯ lms/local/include/smtp.local.php
# ============================================================
mkdir -p "$SCRIPT_DIR/lms/local/include"
SMTP_FILE="$SCRIPT_DIR/lms/local/include/smtp.local.php"

cat > "$SMTP_FILE" << EOF
<?php
// Сгенерировано setup_smtp.sh — не коммитится в git (lms/local/include/ в .gitignore).
// Generated by setup_smtp.sh — not committed to git (lms/local/include/ is gitignored).
return [
    'SMTP_HOST'       => '${SMTP_HOST}',
    'SMTP_PORT'       => '${SMTP_PORT}',
    'SMTP_SECURE'     => '${SMTP_SECURE}',
    'SMTP_AUTH'       => '${SMTP_AUTH}',
    'SMTP_FROM_EMAIL' => '${SMTP_FROM_EMAIL}',
    'SMTP_PASSWORD'   => '${SMTP_PASSWORD}',
];
EOF
chmod 600 "$SMTP_FILE"
success "Создан / Created: lms/local/include/smtp.local.php (chmod 600)"

# ============================================================
# 3. ПЕРЕЗАПУСК php / RESTART php
# ============================================================
echo ""
if docker compose version >/dev/null 2>&1; then
  DC="docker compose"
elif docker-compose --version >/dev/null 2>&1; then
  DC="docker-compose"
else
  DC=""
fi

if [ -n "$DC" ] && $DC ps php >/dev/null 2>&1 && [ -n "$($DC ps -q php 2>/dev/null)" ]; then
  read -p "Перезапустить контейнер php сейчас, чтобы применить настройки? / Restart the php container now to apply? (Y/n): " DO_RESTART
  DO_RESTART=${DO_RESTART:-Y}
  if [[ "$DO_RESTART" =~ ^[Yy]$ ]]; then
    $DC restart php
    success "Контейнер php перезапущен / php container restarted"
  else
    info "Не забудьте выполнить: $DC restart php / Don't forget to run: $DC restart php"
  fi
else
  info "Контейнер php не запущен — настройки применятся при следующем запуске (install.sh/update.sh)."
  info "php container is not running — settings will apply on the next start (install.sh/update.sh)."
fi

echo ""
echo "=============================================="
success "Настройка SMTP завершена / SMTP setup complete"
echo "=============================================="
echo ""
echo "SMTP_HOST   = ${SMTP_HOST}"
echo "SMTP_PORT   = ${SMTP_PORT}"
echo "SMTP_SECURE = ${SMTP_SECURE}"
echo "SMTP_AUTH   = ${SMTP_AUTH}"
echo "SMTP_FROM   = ${SMTP_FROM_EMAIL}"
echo ""
